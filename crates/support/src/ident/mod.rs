//! Чеканка идентификаторов.
//!
//! Единственное место, где выбирается версия UUID. Прикладные крейты дают
//! идентификаторам доменные имена и правила, но саму генерацию берут отсюда,
//! чтобы смена схемы (например, на упорядоченный по времени v7) была одним
//! изменением.

use uuid::Uuid;

/// Новый случайный идентификатор (UUID v4).
///
/// Каждый вызов даёт уникальное значение; стабильность идентификатора при
/// повторе операции — обязанность вызывающего, не генератора.
pub fn fresh_uuid() -> Uuid {
  Uuid::new_v4()
}

/// Детерминированно выводит идентификатор из базы и имени (UUID v5).
///
/// Одна база и одно имя всегда дают один результат, разные имена при одной
/// базе — разные. Используется, когда одна операция создаёт несколько
/// идентификаторов, а их число заранее неизвестно: вызывающий получает одну
/// свежую базу и выводит из неё идентификатор для каждого имени.
pub fn derive_uuid(base: Uuid, name: &[u8]) -> Uuid {
  Uuid::new_v5(&base, name)
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn fresh_ids_are_unique() {
    assert_ne!(fresh_uuid(), fresh_uuid());
  }

  #[test]
  fn derived_ids_depend_on_base_and_name() {
    let base = fresh_uuid();

    assert_eq!(derive_uuid(base, b"room-1"), derive_uuid(base, b"room-1"));
    assert_ne!(derive_uuid(base, b"room-1"), derive_uuid(base, b"room-2"));
    assert_ne!(
      derive_uuid(base, b"room-1"),
      derive_uuid(fresh_uuid(), b"room-1")
    );
  }
}
