use crate::{CommittedTransition, PresenceDeliveryError};
use std::{future::Future, pin::Pin};

pub type PresenceDeliveryFuture<'a> = Pin<Box<dyn Future<Output = Result<(), PresenceDeliveryError>> + Send + 'a>>;

pub trait PresenceCommitDelivery: Send + Sync {

  /// Обрабатывает переход, возвращённый после успешной фиксации операции
  /// в [`PresenceStore`].
  ///
  /// [`PresenceService`] вызывает этот метод только после того, как хранилище
  /// успешно изменило основное состояние и вернуло [`CommittedTransition`].
  /// К моменту вызова операция уже зафиксирована и не может быть отменена ошибкой
  /// последующей обработки.
  ///
  /// В локальном режиме реализация передаёт каноническое событие локальному
  /// проектору. Успешное завершение означает, что событие обработано проектором
  /// и поставлено в очереди доступных локальных получателей.
  ///
  /// В Redis-режиме запись канонического события в outbox является частью
  /// атомарной операции хранилища. Реализация не должна публиковать это событие
  /// повторно; дальнейшую публикацию выполняет отдельный outbox publisher.
  ///
  /// Переход без канонического события не требует доставки и обрабатывается
  /// успешно. Повторная обработка того же перехода должна быть безопасной.
  ///
  /// # Errors
  ///
  /// Возвращает [`PresenceDeliveryError`], если обязательную обработку перехода
  /// выполнить не удалось. Ошибка не отменяет уже зафиксированную операцию.
  /// Повтор должен использовать исходную операцию, тот же переход и тот же
  /// `event_id`.
  fn after_commit<'a>(&'a self, transition: &'a CommittedTransition) -> PresenceDeliveryFuture<'a>;
}