-- Фрагмент для встраивания в чужие Lua-скрипты: проверяет, что lease по ключу
-- принадлежит вызывающему в текущем периоде владения, не выполняя никаких
-- других действий.
--
-- Использование в transition хранилища: фрагмент подставляется в начало
-- скрипта, ключ lease передаётся в KEYS, token периода (`lease_value(token)`,
-- формат `lease:<owner>:<fence>`) — в ARGV, и первой строкой идёт
--
--   if not holds_lease(KEYS[n], ARGV[m]) then return redis.error_reply("...") end
--
-- Проверка и изменение состояния остаются одной атомарной операцией Redis:
-- между ними другой клиент не может забрать или продлить lease.
--
-- Сравнение побайтное со значением всего token, поэтому не проходит не только
-- чужой владелец, но и работа из прошлого периода того же владельца: после
-- release или истечения и нового захвата fence другой. Отсутствующий ключ
-- (GET -> false) никому не принадлежит, поэтому истёкший lease даёт false без
-- отдельной проверки TTL.

local function holds_lease(key, token_value)
  return redis.call("GET", key) == token_value
end
