/// Показывает, имеет ли смысл повторять обработку события.
///
/// Этот класс не управляет повторной доставкой самостоятельно. Он только
/// передаёт решение следующему уровню — например, JetStream consumer-у:
///
/// - [`Retryable`](Self::Retryable) означает, что причина может исчезнуть и
///   событие следует попробовать обработать ещё раз;
/// - [`Permanent`](Self::Permanent) означает, что повтор с теми же данными не
///   исправит ошибку.
///
/// Конкретный транспорт сам решает, как выполнить это решение. Например,
/// JetStream может преобразовать `Retryable` в `NAK`, а `Permanent` — в
/// публикацию в DLQ и `TERM`.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ProcessingErrorClass {
    /// Временная ошибка, после которой обработку можно повторить.
    Retryable,

    /// Постоянная ошибка: повторная обработка тех же данных не поможет.
    Permanent,
}
